// ── Renderer ─────────────────────────────────────────────────────────
interface PixelIconProps {
  grid: string[]
  size?: number
  label?: string
}

export function PixelIcon({ grid, size = 32, label }: PixelIconProps) {
  const cols = grid[0].length
  const rows = grid.length
  return (
    <svg
      width={size}
      height={(size * rows) / cols}
      viewBox={`0 0 ${cols} ${rows}`}
      shapeRendering="crispEdges"
      aria-label={label}
      role={label ? 'img' : undefined}
      aria-hidden={!label}
    >
      {grid.map((row, y) =>
        row.split('').map((ch, x) => {
          if (ch === '.' || ch === ' ') return null
          return (
            <rect
              key={`${x}-${y}`}
              x={x}
              y={y}
              width="1"
              height="1"
              fill={ch === '*' ? 'var(--paper)' : 'currentColor'}
            />
          )
        })
      )}
    </svg>
  )
}
