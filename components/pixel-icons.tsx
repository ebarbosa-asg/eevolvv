const EVO_GRIDS = [EVO_MONKEY, EVO_APE, EVO_HOMINID, EVO_HUMAN_EARLY, EVO_HUMAN_MODERN]

interface EvoFrameProps {
  which: number
  size?: number
  on?: boolean
}

export function EvoFrame({ which, size = 40, on = true }: EvoFrameProps) {
  const grid = EVO_GRIDS[which] ?? EVO_GRIDS[0]
  const cols = grid[0].length
  const rows = grid.length
  return (
    <svg
      width={size}
      height={(size * rows) / cols}
      viewBox={`0 0 ${cols} ${rows}`}
      shapeRendering="crispEdges"
      className={on ? 'on' : ''}
      aria-hidden="true"
    >
      {grid.map((row, y) =>
        row.split('').map((ch, x) =>
          ch === '#' ? (
            <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill="currentColor" />
          ) : null
        )
      )}
    </svg>
  )
}

